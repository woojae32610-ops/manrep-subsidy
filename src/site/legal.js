// 이용약관 · 개인정보처리방침 페이지 내용 (site/terms.html, site/privacy.html)
// - 이 사이트는 로그인·댓글·문의 양식이 없고 쿠키·분석 도구도 안 쓰므로, 사실 그대로 "수집하지 않는다"고 적는다.
// - 나중에 방문자 분석(GA 등)이나 문의 양식을 붙이면 여기 문구도 같이 고쳐야 한다.
import { esc } from '../lib/util.js';

const ymdKo = (iso) => { const [y, m, d] = String(iso).split('-'); return `${y}년 ${Number(m)}월 ${Number(d)}일`; };

export function legalPages({ site, sourceNames, today }) {
  const name = esc(site.name);
  const cafe = esc(site.cafeName);
  const op = esc(site.legal?.operator || `${site.cafeName} 카페 운영진`);
  const eff = ymdKo(site.legal?.effective || today);
  const cafeLink = `<a href="${esc(site.cafeUrl)}" target="_blank" rel="noopener">${cafe} 카페</a>`;

  const terms = `
<h1>이용약관</h1>
<p class="eff">시행일 ${eff}</p>

<h2>제1조 (목적)</h2>
<p>이 약관은 ${op}(이하 "운영자")이 운영하는 「${name}」(이하 "사이트")을 이용할 때 지켜야 할 내용을 정합니다.</p>

<h2>제2조 (서비스 내용)</h2>
<p>사이트는 ${esc(sourceNames)} 등 공공데이터로 공개된 지원사업 공고를 모아, 자격 조건·지원 내용·기한을 쉬운 말로 정리해 보여주는 <b>정보 안내 서비스</b>입니다. 사이트는 지원사업의 접수·심사·선정과 아무 관계가 없으며, 신청은 각 공고의 접수 기관에서 합니다.</p>

<h2>제3조 (정보의 성격과 한계)</h2>
<ol>
  <li>요약·체크리스트·분류는 AI(인공지능)가 공고 원문을 읽고 작성한 것으로, 원문과 다르거나 빠진 내용이 있을 수 있습니다.</li>
  <li>공고 내용은 기관 사정에 따라 예고 없이 바뀔 수 있습니다.</li>
  <li>신청 자격·금액·기한 등 중요한 사항은 반드시 공고 원문과 접수 기관에서 확인해야 합니다. 사이트 정보만 믿고 내린 판단이나 그로 인한 손해에 대해 운영자는 법령이 허용하는 범위에서 책임을 지지 않습니다.</li>
</ol>

<h2>제4조 (저작권과 출처)</h2>
<ol>
  <li>공고 원문의 권리는 해당 기관에 있습니다. 사이트는 공공데이터를 출처 표시와 함께 이용합니다.</li>
  <li>사이트의 요약문·체크리스트·화면 구성에 대한 권리는 운영자에게 있습니다. 페이지 링크는 자유롭게 공유할 수 있고, 요약문을 옮겨 쓸 때는 출처(사이트 이름)를 밝혀 주세요. 영리 목적의 무단 복제·재배포는 금지합니다.</li>
</ol>

<h2>제5조 (외부 링크)</h2>
<p>사이트에서 연결되는 외부 사이트(정부24, 기업마당, K-Startup, 각 접수 기관, 네이버 카페 등)의 내용과 개인정보 처리는 해당 사이트의 책임입니다.</p>

<h2>제6조 (서비스 변경·중단)</h2>
<p>운영자는 서비스 내용을 바꾸거나 운영을 멈출 수 있으며, 중요한 변경은 사이트에 알립니다.</p>

<h2>제7조 (문의)</h2>
<p>잘못된 정보나 문의 사항은 ${cafeLink}로 알려 주세요.</p>

<p class="eff">이 약관은 ${eff}부터 적용합니다.</p>`;

  const privacy = `
<h1>개인정보처리방침</h1>
<p class="eff">시행일 ${eff}</p>
<p>「${name}」(이하 "사이트")은 방문자의 개인정보를 소중히 여기며, 다음과 같이 처리합니다.</p>

<h2>1. 수집하는 개인정보</h2>
<p>사이트에는 회원가입·로그인·댓글·문의 양식이 없으며, 이름·연락처·이메일 등 <b>개인정보를 직접 수집하지 않습니다.</b></p>

<h2>2. 자동으로 생기는 정보</h2>
<p>사이트는 GitHub Pages(GitHub, Inc.)에 올려져 있어, 접속할 때 IP 주소·접속 시각 같은 기록이 GitHub 서버에 남을 수 있습니다. 이 기록은 GitHub의 개인정보 처리방침에 따라 처리되며, 운영자는 이를 열람하거나 따로 모으지 않습니다.</p>

<h2>3. 쿠키와 추적</h2>
<p>사이트는 쿠키, 방문자 분석 도구(예: Google Analytics), 광고 추적 코드를 사용하지 않습니다. 필터·검색 상태는 주소창(URL)에만 남고 방문자 기기에 저장되지 않습니다.</p>

<h2>4. 외부 서비스</h2>
<ul>
  <li>글꼴(Pretendard)을 외부 CDN(jsDelivr)에서 불러오며, 이 과정에서 방문자의 IP 주소가 해당 서비스에 전달될 수 있습니다.</li>
  <li>사이트에서 연결되는 정부24, 기업마당, K-Startup, 각 접수 기관의 사이트와 네이버 카페는 각자의 개인정보처리방침을 따릅니다.</li>
</ul>

<h2>5. 문의</h2>
<p>개인정보 관련 문의는 ${op}에게 ${cafeLink}를 통해 해 주세요.</p>

<h2>6. 변경</h2>
<p>이 방침이 바뀌면 이 페이지에 바뀐 내용과 날짜를 함께 알립니다.</p>`;

  return [
    { file: 'terms.html', title: '이용약관', description: `${site.name} 이용약관 — 정보 안내 서비스의 성격, 정보의 한계, 저작권과 출처, 외부 링크.`, body: terms },
    { file: 'privacy.html', title: '개인정보처리방침', description: `${site.name} 개인정보처리방침 — 개인정보를 직접 수집하지 않으며 쿠키·분석 도구를 쓰지 않습니다.`, body: privacy },
  ];
}
